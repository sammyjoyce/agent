#[path = "export_protocol/swift.rs"]
mod swift;
#[path = "../../tests/fixtures/tool_merge.rs"]
mod tool_merge;
use std::{
    fs,
    path::{Path, PathBuf},
};

use agent_cli::protocol;
use agent_cli::protocol::{
    AllocationDecision, DelegationDecision, HistoryImportBatch, HistoryImportReceipt, RuntimeEvent,
    RuntimeRequest, TaskOutcome,
};
use anyhow::{Context, Result, ensure};
use schemars::schema_for;
use ts_rs::{Config, TS};

fn main() -> Result<()> {
    let output = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("runtime/src/generated");
    fs::create_dir_all(&output)?;
    let config = Config::from_env()
        .with_out_dir(&output)
        .with_import_extension(Some("js"));
    RuntimeRequest::export_all(&config)?;
    RuntimeEvent::export_all(&config)?;
    agent_cli::native::NativeCommand::export_all(&config)?;
    agent_cli::native::NativeEvent::export_all(&config)?;
    agent_cli::notifications::ApnsConfig::export_all(&config)?;
    agent_cli::notifications::NotificationTarget::export_all(&config)?;
    fs::write(
        output.join("apns.schema.json"),
        serde_json::to_string_pretty(&schema_for!(agent_cli::notifications::ApnsConfig))?,
    )?;
    agent_cli::background::BackgroundTaskInput::export_all(&config)?;
    agent_cli::background::BackgroundCheckpoint::export_all(&config)?;
    TaskOutcome::export_all(&config)?;
    DelegationDecision::export_all(&config)?;
    AllocationDecision::export_all(&config)?;
    HistoryImportBatch::export_all(&config)?;
    HistoryImportReceipt::export_all(&config)?;
    agent_cli::browser::BrowserRequest::export_all(&config)?;
    agent_cli::browser::BrowserReply::export_all(&config)?;
    agent_cli::browser::BrowserHelperInput::export_all(&config)?;
    agent_cli::browser::BrowserNativeControlRequest::export_all(&config)?;
    agent_cli::browser::BrowserConfig::export_all(&config)?;
    agent_cli::browser::BrowserBinding::export_all(&config)?;
    fs::write(
        output.join("browser.schema.json"),
        serde_json::to_string_pretty(&schema_for!(agent_cli::browser::BrowserHelperInput))?,
    )?;
    fs::write(
        output.join("request.schema.json"),
        serde_json::to_string_pretty(&schema_for!(RuntimeRequest))?,
    )?;
    fs::write(
        output.join("event.schema.json"),
        serde_json::to_string_pretty(&schema_for!(RuntimeEvent))?,
    )?;
    let native =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("ios/Sources/AgentCore/Generated.swift");
    fs::create_dir_all(
        native
            .parent()
            .ok_or_else(|| anyhow::anyhow!("Missing native directory"))?,
    )?;
    fs::write(
        native,
        swift::generate(&[
            serde_json::to_value(schema_for!(agent_cli::native::NativeCommand))?,
            serde_json::to_value(schema_for!(agent_cli::native::NativeEvent))?,
            serde_json::to_value(schema_for!(agent_cli::notifications::NotificationTarget))?,
        ])? + &format!(
            "public enum AttachmentLimits {{\n    public static let maximumBytes = {}\n    public static let chunkBytes = {}\n    public static let maximumCount = {}\n    public static let maximumNameBytes = {}\n}}\n",
            agent_cli::attachments::MAX_ATTACHMENT_BYTES,
            agent_cli::attachments::ATTACHMENT_CHUNK_BYTES,
            agent_cli::attachments::MAX_ATTACHMENTS,
            agent_cli::attachments::MAX_ATTACHMENT_NAME_BYTES
        ),
    )?;
    fs::write(
        output.join("attachment-limits.ts"),
        format!(
            "// Generated by make bindings. Do not edit.\nexport const MAX_ATTACHMENT_BYTES = {};\nexport const ATTACHMENT_CHUNK_BYTES = {};\nexport const MAX_ATTACHMENTS = {};\nexport const MAX_ATTACHMENT_NAME_BYTES = {};\nexport const ATTACHMENT_STAGING_MILLIS = {};\n",
            agent_cli::attachments::MAX_ATTACHMENT_BYTES,
            agent_cli::attachments::ATTACHMENT_CHUNK_BYTES,
            agent_cli::attachments::MAX_ATTACHMENTS,
            agent_cli::attachments::MAX_ATTACHMENT_NAME_BYTES,
            agent_cli::attachments::ATTACHMENT_STAGING_MILLIS
        ),
    )?;
    let fixtures =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("ios/Tests/AgentCoreTests/Fixtures");
    fs::create_dir_all(&fixtures)?;
    validate_tool_merge_traces(&fixtures)?;
    let schema = serde_json::to_value(schema_for!(agent_cli::native::NativeEvent))?;
    let events = swift::samples(&schema, &schema)?
        .into_iter()
        .map(|value| {
            let event: agent_cli::native::NativeEvent = serde_json::from_value(value)?;
            serde_json::to_string(&event)
        })
        .collect::<std::result::Result<Vec<_>, serde_json::Error>>()?;
    fs::write(fixtures.join("events.ndjson"), events.join("\n") + "\n")?;
    let schema = serde_json::to_value(schema_for!(agent_cli::native::NativeCommand))?;
    let commands = swift::samples(&schema, &schema)?
        .into_iter()
        .map(|value| {
            let command: agent_cli::native::NativeCommand = serde_json::from_value(value)?;
            serde_json::to_string(&command)
        })
        .collect::<std::result::Result<Vec<_>, serde_json::Error>>()?;
    fs::write(fixtures.join("commands.ndjson"), commands.join("\n") + "\n")?;
    // ts-rs can leave trailing spaces before a field's generated doc comment.
    // Normalize at the producer so checked-in bindings regenerate cleanly.
    for entry in fs::read_dir(&output)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "ts") {
            let source = fs::read_to_string(&path)?;
            let formatted = source
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n")
                + "\n";
            if source != formatted {
                fs::write(path, formatted)?;
            }
        }
    }
    Ok(())
}

fn validate_tool_merge_traces(fixtures: &Path) -> Result<()> {
    let traces: tool_merge::Traces =
        serde_json::from_slice(&fs::read(fixtures.join("tool-merge-traces.json"))?)?;
    ensure!(
        traces.version == 1 && !traces.cases.is_empty(),
        "Unsupported tool merge trace contract"
    );
    for case in traces.cases {
        ensure!(!case.name.is_empty(), "A tool merge trace needs a name");
        for step in case.steps {
            ensure!(
                !step.older_page
                    || matches!(step.event, protocol::RuntimeEventKind::History { .. }),
                "Only a history frame can be an older page"
            );
            let native = agent_cli::native::project(&step.event)
                .context("A tool trace event must have a native projection")?;
            let _: agent_cli::native::NativeEvent =
                serde_json::from_slice(&serde_json::to_vec(&native)?)?;
        }
        let expected = protocol::RuntimeEventKind::Message {
            message: protocol::HistoryMessage {
                entry_id: case.expected.entry_id,
                text: case.expected.text,
                tool: Some(case.expected.tool),
                presentation: case.expected.presentation,
                role: protocol::HistoryRole::Tool,
                continuation: false,
                final_chunk: true,
                notice_origin: None,
                attachments: None,
            },
        };
        let native = agent_cli::native::project(&expected)
            .context("A tool trace result must have a native projection")?;
        let _: agent_cli::native::NativeEvent =
            serde_json::from_slice(&serde_json::to_vec(&native)?)?;
    }
    Ok(())
}
